/**
 * Отказ проверки осмысленности **по состоянию**, а не по поломке.
 *
 * Отдельный тип нужен ровно за тем же, зачем `SessionError`: маршрут обязан
 * отличать «этот вопрос уже подтверждён» от «в базе пропало задание». Пока
 * различия не было, оба ловились одним `catch` и уезжали в 409 своим текстом —
 * то есть внутренняя поломка не попадала ни в обработчик ошибок, ни в журнал
 * аварий (`server-error`), а её сообщение отдавалось наружу как обычный отказ
 * состояния. Всё, что не `IntegrityError`, обязано остаться пятисоткой.
 */
export type IntegrityErrorCode =
  /** Вопрос не ждёт повторного ответа: уже подтверждён либо не отмечался. */
  | 'item-not-pending'
  /** Занятие завершено или проверку не поддерживает. */
  | 'run-not-reviewable'
  /** Проверяемый ответ переписан между отметкой и повтором. */
  | 'attempt-changed'
  /** Проверки этого занятия нет. */
  | 'review-not-found';

export class IntegrityError extends Error {
  constructor(
    readonly code: IntegrityErrorCode,
    message: string,
  ) {
    super(message);
    this.name = 'IntegrityError';
  }
}
