/**
 * Реестр в том виде, в каком его видит допуск: одно решение о том, кто какое
 * соединение получает.
 *
 * Веток две, и они — две стороны одного вопроса «кто пришёл». Ученик за экраном
 * получает пишущее соединение аренды и будит прогрев; оператор, зашедший в
 * чужую семью, получает второе соединение с `PRAGMA query_only = ON` и не будит
 * ничего. Разведи их по двум местам — и новая точка вызова забудет ровно одну.
 *
 * Отдельным модулем, а не замыканием в `buildServer`: выбор ветки — это и есть
 * второй замок имперсонации, и проверяться он обязан без поднятого сервера.
 */
import type { TenantOpener, TenantRequester } from './auth.js';
import type { Tenant } from './tenant-registry.js';
import type { ImpersonationTenants } from './admin/impersonation-tenants.js';

export interface CreateTenantOpenerOptions {
  /** Реестр детских баз. Аренду открывает он — и для оператора тоже. */
  tenants: { open(childId: string): Tenant };
  /** Соединения только для чтения, которыми смотрят чужие семьи. */
  impersonations: Pick<ImpersonationTenants, 'view'>;
  /**
   * Будильник прогрева. Необязателен: воркер отключается опцией сервера, и
   * тогда будить некого.
   */
  wake?: (childId: string) => void;
}

/** Собирает опенер, которым допуск открывает базу ребёнка. */
export function createTenantOpener(options: CreateTenantOpenerOptions): TenantOpener {
  return {
    open(childId: string, bearer: TenantRequester): Tenant {
      // Аренда открывается обычным путём даже под заходом оператора: миграция,
      // посев и координаторы обязаны отработать так же, как для настоящего
      // входа, — оператор смотрит на то, что видит семья, а не на её слепок.
      const tenant = options.tenants.open(childId);

      // Второй замок. Стоит до будильника намеренно: заход оператора — не
      // «ребёнок вернулся за экран», и всё, что ниже, к нему не относится.
      if (bearer.impersonated) return options.impersonations.view(tenant);

      // Будильник только по новому в обходе ребёнку: вернувшийся после перерыва
      // не должен досиживать чужую паузу, а занимающийся не должен будить
      // диспетчер каждым своим запросом (см. `wake`).
      //
      // И только по браузерному предъявителю. Агент опрашивает `gate/status`
      // раз в двадцать секунд и активностью ребёнка не считается: брошенный
      // ребёнок в обход не попадает, то есть в `#served` его нет никогда, и
      // каждый его опрос срывал бы паузу — получасовой отступ по недоступному
      // codex не наступал бы вовсе. Родитель за сводкой — тоже не ученик за
      // экраном, и греть по его запросу нечего.
      if (bearer.kind === 'browser') options.wake?.(childId);
      return tenant;
    },
  };
}
