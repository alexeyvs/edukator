/**
 * Отступ по теме, провалившей фоновую подготовку.
 *
 * Отступ по недоступной модели (`backoffDelay` диспетчера) отвечает на вопрос
 * «жив ли codex» и тормозит обход целиком. Этот отвечает на другой: модель жива
 * и отвечает, но по **этой** теме её ответ не проходит проверку — раз за разом
 * и по одной и той же причине. Без отдельного отступа такая тема съедает всё:
 * долив берёт до `MAX_BATCHES_PER_TOPIC` батчей, батч — до трёх попыток
 * генератора плюс проверяющий, обход идёт раз в минуту, а суточная квота у
 * ребёнка одна на всё. На проде это выглядело так: 25 августа вся квота в 60
 * вызовов сгорала за первый час после московской полуночи на двух безнадёжных
 * темах, а остальные двадцать тем и персональные материалы не получали ничего
 * до следующих суток. Ребёнок при этом видел работающее приложение с
 * остывающим банком.
 *
 * Состояние процессное и в базе не лежит — сознательно, по тем же причинам, что
 * и отступ диспетчера. Оно описывает не тему, а текущую работоспособность связки
 * «эта модель на этом промпте»: перезапуск сервера обычно и означает, что
 * промпт или проверка изменились, и держать после него старый запрет значило бы
 * прятать как раз ту тему, ради которой перезапуск и делался.
 */

/** Первая пауза по провалившейся теме; дальше удваивается. */
export const TOPIC_BACKOFF_BASE_MS = 15 * 60 * 1000;

/**
 * Потолок паузы. Шесть часов, а не сутки: тема может провалиться и по разовой
 * причине (сорванный вызов, неудачный набор прошлых формулировок), а суточный
 * потолок означал бы, что одна такая осечка снимает тему с прогрева до
 * следующего дня — то есть ровно до того момента, когда ученик за неё сядет.
 */
export const TOPIC_BACKOFF_MAX_MS = 6 * 60 * 60 * 1000;

/**
 * Пауза после `failures` провалов подряд. Отдельной функцией потому же, почему
 * `nextDisputeRetryDelay` и `backoffDelay`: тесты гоняют отступ на паузах в
 * миллисекунды, и на них постоянная задержка неотличима от растущей.
 */
export function topicBackoffDelay(failures: number): number {
  if (failures <= 0) return 0;
  return Math.min(TOPIC_BACKOFF_BASE_MS * 2 ** (failures - 1), TOPIC_BACKOFF_MAX_MS);
}

interface TopicState {
  failures: number;
  until: number;
}

/**
 * Отступы тем **одного** ребёнка.
 *
 * Экземпляр на ребёнка, а не общий на процесс: идентификаторы тем глобальны
 * (`russian.mestoimenie` у всех один), и общий счётчик снимал бы тему с прогрева
 * всей семье из-за неудач одного ученика — у которого и профиль, и прошлые
 * формулировки, и сложность свои.
 */
export class TopicBackoff {
  #topics = new Map<string, TopicState>();

  /** Держится ли тема отступом прямо сейчас. */
  blocked(topicId: string, now: Date): boolean {
    const state = this.#topics.get(topicId);
    return state !== undefined && now.getTime() < state.until;
  }

  /** Отмечает провал и возвращает назначенную паузу. */
  noteFailure(topicId: string, now: Date): number {
    const failures = (this.#topics.get(topicId)?.failures ?? 0) + 1;
    const delay = topicBackoffDelay(failures);
    this.#topics.set(topicId, { failures, until: now.getTime() + delay });
    return delay;
  }

  /**
   * Отмечает удачный долив: снимается и пауза, и счётчик. Именно счётчик, а не
   * только пауза: тема, спотыкающаяся раз в сутки, иначе к концу недели уходила
   * бы в шестичасовой отступ с первого же провала.
   */
  noteSuccess(topicId: string): void {
    this.#topics.delete(topicId);
  }
}
