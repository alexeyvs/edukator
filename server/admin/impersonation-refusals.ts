/**
 * Счётчик отказанных попыток записи под заходом оператора.
 *
 * Считает он ровно первый замок — отказ `read-only` в `resolveTenant`, — и
 * нужен одному месту: записи `impersonation-end` в журнале действий. Без него
 * конец захода говорит «оператор посмотрел и вышел» одинаково и там, где
 * оператор действительно смотрел, и там, где он двадцать раз попробовал
 * ответить за чужого ребёнка.
 *
 * Счётчик процессный, а не в `control.db`, по двум причинам. Запись в базу на
 * каждый отказ означала бы, что закрытый маршрут всё-таки умеет заставить нас
 * писать — то есть отказ стоил бы дороже разрешения. И читает его тот же
 * процесс, который отказ выдал: заход живёт пятнадцать минут и перезапуск
 * сервера не переживает вовсе.
 *
 * Ключ — оператор, а не токен захода: живая имперсонация у оператора ровно
 * одна (`startImpersonation` гасит предыдущую тем же `UPDATE`), а токена у
 * записи о конце может уже не быть — её пишет и выход, и вытеснение новым
 * заходом.
 */
export class ImpersonationRefusals {
  readonly #counts = new Map<string, number>();

  /** Отмечает отказ и возвращает новое значение счётчика. */
  record(adminId: string): number {
    const next = (this.#counts.get(adminId) ?? 0) + 1;
    this.#counts.set(adminId, next);
    return next;
  }

  /** Сколько отказов накопилось. Ни разу не отказывали — ноль, а не `undefined`. */
  count(adminId: string): number {
    return this.#counts.get(adminId) ?? 0;
  }

  /**
   * Забирает счётчик и обнуляет его. Читать и сбрасывать раздельно нельзя:
   * между двумя вызовами успевает начаться следующий заход, и его первый отказ
   * либо потерялся бы, либо приписался бы к прошлой записи.
   */
  take(adminId: string): number {
    const count = this.count(adminId);
    this.#counts.delete(adminId);
    return count;
  }
}
