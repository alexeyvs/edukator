import { describe, expect, it } from 'vitest';
import { isParentPin } from './pin-format';

describe('формат PIN родителя на клиенте', () => {
  // Границы вписаны руками: формат PIN — межмодульный инвариант, копия
  // серверного `/^\d{6,12}$/u`. Сдвинутая на клиенте граница отключает кнопку
  // по правилу, которого на сервере уже нет, — и наоборот, шлёт заведомый 400.
  it('держит границы серверного формата', () => {
    for (const bad of ['', '1', '12345', '1234567890123', '12345a', ' 123456', '123 456']) {
      expect(isParentPin(bad)).toBe(false);
    }
    for (const good of ['123456', '1234567', '123456789012']) {
      expect(isParentPin(good)).toBe(true);
    }
  });

  // `\d` с флагом `u` — только ASCII-цифры, но арабско-индийские цифры сервер
  // не примет, и принятые здесь дали бы 400 с виду исправному PIN.
  it('не считает цифрами всё, что на них похоже', () => {
    expect(isParentPin('١٢٣٤٥٦')).toBe(false);
  });
});
