/**
 * Целый адрес одноразовой ссылки. Сервер отдаёт только путь: за обратным прокси
 * он не знает ни схемы, ни внешнего имени, и склеенный им `http://` увёл бы
 * открывающего мимо TLS. Адрес собирает клиент — он по нему и пришёл.
 *
 * Копия ровно одна: ссылки показывают два экрана — состав семьи (устройство
 * ребёнка) и админка (пароль родителя), — и разъехавшись, они отдавали бы одну
 * и ту же строку по разным адресам.
 */
export function inviteUrl(path: string): string {
  return new URL(path, window.location.origin).toString();
}
