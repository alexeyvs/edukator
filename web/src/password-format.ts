/**
 * Границы пароля родителя на клиенте — копия серверных `MIN_PASSWORD_LENGTH`
 * (`server/control-db.ts`) и `MAX_SECRET_LENGTH` (`server/secrets.ts`):
 * импортировать `server/` клиенту нечем, а без проверки на месте кнопка слала
 * бы заведомый 400.
 *
 * Копия ровно одна на весь клиент — по той же причине, что и у формата PIN
 * (`pin-format.ts`): второй экземпляр разъезжается с первым молча. Раньше она
 * жила в `InviteScreen`, где была одна форма пароля; форм стало три — ссылка,
 * смена пароля родителем и пароль, поставленный оператором, — и предел,
 * лежащий внутри одного экрана, к остальным двум приезжает копированием.
 *
 * Числа закреплены `password-format.test.ts` вписанными руками: тест,
 * считающий ожидание из той же константы, её подмену не ловит.
 */
export const MIN_PASSWORD_LENGTH = 10;

/**
 * Верхняя граница есть и у неё есть смысл: сервер отвергает пароль длиннее
 * `MAX_SECRET_LENGTH` **до** KDF, и без такой же проверки здесь длинный пароль
 * возвращался бы отказом, который форма объяснить не умеет.
 */
export const MAX_PASSWORD_LENGTH = 128;

/** Годится ли строка в пароль родителя. */
export function isParentPassword(value: string): boolean {
  return value.length >= MIN_PASSWORD_LENGTH && value.length <= MAX_PASSWORD_LENGTH;
}
