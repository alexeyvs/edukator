/**
 * Формат PIN родителя на клиенте — копия серверного `PARENT_PIN_PATTERN`
 * (`server/parent-pin.ts`): импортировать `server/` клиенту нечем, а без
 * проверки на месте кнопка слала бы заведомый 400.
 *
 * Копия ровно одна на весь клиент. Второй экземпляр разъезжается с первым
 * молча: расширенный на сервере формат оставил бы экран, где кнопка отключена
 * по вчерашнему правилу и запроса не уходит вовсе — то есть без ошибки, по
 * которой это можно найти. Границы закреплены `pin-format.test.ts` числами,
 * вписанными руками: тест, считающий ожидание из той же строки, подмену не
 * ловит.
 */
export const PARENT_PIN_PATTERN = /^\d{6,12}$/u;

/** Годится ли строка в PIN родителя. */
export function isParentPin(value: string): boolean {
  return PARENT_PIN_PATTERN.test(value);
}
